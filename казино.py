def spin_step(step, total_steps, t, win_label, money_label, credit_label):
    global money
    global ticket

    if step >= total_steps:
        nums = [random.randint(0, 7) for _ in range(3)]
        t["text"] = f"{nums[0]} {nums[1]} {nums[2]}"

        if len(set(nums)) == 1:
            win_label["text"] = "Выигрыш!"
            win_label.config(fg="green")
            ticket += 1
        else:
            win_label["text"] = "Проигрыш"
            win_label.config(fg="red")
            money -= 1

        money_label.config(text=f"Деньги: {money}")
        credit_label.config(text=f"Начальное количество денег: {credit}")
        

        if money <= 0:
            win_label["text"] = "Вы проиграли всё!"
            win_label.config(fg="red")

        else:
            root.after(1500, enable_dep_button)
        return
        
    t["text"] = f"{random.randint(0, 7)} {random.randint(0, 7)} {random.randint(0, 7)}"
    root.after(20, lambda: spin_step(step + 1, total_steps, t, win_label, money_label, credit_label))



